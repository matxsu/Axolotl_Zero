#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn dictionary_not_empty() {
        assert!(!DEFAULT_KEYS.is_empty());
    }

    #[test]
    fn factory_keys_present() {
        assert!(DEFAULT_KEYS.contains(&[0xFF; 6]));
        assert!(DEFAULT_KEYS.contains(&[0x00; 6]));
    }

    #[test]
    fn all_keys_are_6_bytes() {
        for key in DEFAULT_KEYS {
            assert_eq!(key.len(), 6);
        }
    }

    /// Chaque tentative d'auth coûte ~50ms — un doublon double le coût pour rien.
    #[test]
    fn no_duplicate_keys() {
        let mut seen: Vec<[u8; 6]> = Vec::new();
        for &key in DEFAULT_KEYS {
            assert!(!seen.contains(&key), "doublon: {:02X?}", key);
            seen.push(key);
        }
    }

    #[test]
    fn dictionary_has_reasonable_size() {
        // 200 clés × 16 secteurs × ~50ms auth = ~2.7min max (acceptable pour un dump)
        assert!(DEFAULT_KEYS.len() >= 30);
        assert!(DEFAULT_KEYS.len() <= 300);
    }
}
